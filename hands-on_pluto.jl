md"""
#### 9. Fourier series of a step function and a sawtooth function

Let $g(x)$ and $h(x)$ be a $1$-periodic step function and a $1$ periodic sawtooth function, that is, 

$$\begin{aligned}
  g(x)
& :=
  \begin{cases}
  1, &\ x\in[0,1/2],
  \\
  0, &\ x\in(1/2,1),
  \end{cases}
\\
  g(x)
& :=
  g(x-n),\ 
  x\in[n,n+1),\  
  n\in\mathbb{Z},
\\
  h(x)
& :=x,
\\
  h(x)
& :=h(x-n),\ 
  x\in[n,n+1),\ 
  n\in\mathbb{Z}.
\end{aligned}$$

Their Fourier series are 

$$\begin{aligned}
  g(x)
& \sim
  \frac{1}{2}
  +
  \sum_{k=1}^\infty
  \frac{2}{(2k-1)\pi}
  \sin\bigl(2(2k-1)\pi x\bigr),
\\
  h(x)
& \sim
  \frac{1}{2}
  -
  \sum_{n=1}^\infty
  \frac{1}{n\pi}
  \sin(2\pi nx),
\end{aligned}$$

Set 

$$\begin{aligned}
  S_{2K-1}[g](x)
& =
  \frac{1}{2}
  +
  \sum_{k=1}^K
  \frac{2}{(2k-1)\pi}
  \sin\bigl(2(2k-1)\pi x\bigr)
  \quad 
  (K=1,2,3.\dotsc),
\\
  S_{-1}[g](x)
& :=\frac{1}{2},
\\
  S_N[h](x)
& =
  \frac{1}{2}
  -
  \sum_{n=1}^N
  \frac{1}{n\pi}
  \sin(2\pi nx)
  \qquad
  (N=1,2,3,\dotsc),
\\
  S_0[h](x)
& :=
  \frac{1}{2}.
\end{aligned}$$

On one hand, at the discontinuous points 

$$\begin{aligned}
  S_{2K-1}[g](k)
  =
  \frac{1}{2}
& \rightarrow
  \frac{1}{2}
  =
  \frac{g(k-0)+g(k+0)}{2}
  \quad
  (K\rightarrow\infty),
\\
  S_{2K-1}[g](k+1/2)
  =
  \frac{1}{2}
& \rightarrow
  \frac{1}{2}
  =
  \frac{g(k+1/2-0)+g(k+1/2+0)}{2}
  \quad
  (K\rightarrow\infty),
\\
  S_N[h](k)
  =
  \frac{1}{2}
& \rightarrow
  \frac{1}{2}
  =
  \frac{h(k-0)+h(k+0)}{2}
  \quad
  (N\rightarrow\infty)
\end{aligned}$$

for all $k\in\mathbb{Z}$. On the other hand, we can prove that for any small $\delta>0$

$$\begin{aligned}
  \max_{x\in[\delta,1/2-\delta]\cup[1/2+\delta,1-\delta]}
  \lvert{S_{2K-1}[g](x)-g(x)}\rvert
& \rightarrow
  0
  \quad
  (K\rightarrow\infty),
\\
  \max_{x\in[\delta,1-\delta]}
  \lvert{S_N[h](x)-h(x)}\rvert
& \rightarrow
  0
  \quad
  (N\rightarrow\infty).
\end{aligned}$$

The partial sums oscillate violately as $N$ increases near the discontinuous points. This is called the Gibbs phenomenon.

"""

